package task1;

public class Player {
    public String name;
    public String team;
    
public Player(String name, String team) {
        this.name = name;
        this.team = team;
    }


public String getName() {
        return name;
    }

    public String getTeam() {
        return team;
    }

public void setName(String name) {
        this.name = name;
    }

    public void setTeam(String team) {
        this.team = team;
    }





}
